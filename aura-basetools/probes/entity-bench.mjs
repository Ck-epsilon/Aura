console.log(`entity-bench: ${path.relative(root, cli)}`)
if (!fs.existsSync(cli)) {
  console.error('build first: node build/make-bundle.mjs --pack')
} else {
const readRuns = []
const applyRuns = []
const taskRuns = []
for (let i = 0; i < 3; i += 1) {
  const file = path.join(tmp, `bench-${i}.mjs`)
  fs.writeFileSync(file, makeSource(3300))
  const read = runCli(['basetools', 'read', '--file', file, '--entity', 'function:fn2000'])
  readRuns.push(read.ms)
  if (read.env?.ok !== true) console.error('entity read failed:', JSON.stringify(read.env ?? read.stderr).slice(0, 200))
  const apply = runCli([
    'basetools', 'apply', '--file', file, '--entity', 'function:fn2000', '--op', 'rename', '--new-name', 'fn2000x',
    ...(read.env?.evidence === undefined ? [] : ['--evidence', JSON.stringify(read.env.evidence)]),
  ])
  applyRuns.push(apply.ms)
  taskRuns.push(read.ms + apply.ms)
  if (apply.env?.ok !== true) console.error('entity apply failed:', JSON.stringify(apply.env ?? apply.stderr).slice(0, 200))
}
const imagePath = path.join(tmp, 'one.png')
fs.writeFileSync(imagePath, png)
const image = runCli(['basetools', 'read', '--file', imagePath])
const grep = runCli(['basetools', 'read', '--file', path.join(root, 'src'), '--search', 'entityView', '--max-results', '20'])

console.log(`entity read (10k lines, CLI, n=3)      p50 ${median(readRuns).toFixed(1)} ms`)
console.log(`entity apply (rename, CLI, n=3)        p50 ${median(applyRuns).toFixed(1)} ms`)
console.log(`entity task (read+apply, 2 CLI calls)  p50 ${median(taskRuns).toFixed(1)} ms`)
console.log(`repo grep (src/, CLI)                  ${grep.ms.toFixed(1)} ms  files=${grep.env?.filesScanned ?? '?'} matches=${grep.env?.matches?.length ?? '?'}`)
console.log(`image metadata (1x1 PNG, CLI)          ${image.ms.toFixed(1)} ms  ${image.env?.mime ?? image.env?.error ?? '?'}`)
fs.rmSync(tmp, { recursive: true, force: true })
}
