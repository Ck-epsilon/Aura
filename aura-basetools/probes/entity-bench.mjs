import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { performance } from 'node:perf_hooks'

const root = path.resolve(import.meta.dirname, '..')
const cli = path.join(root, 'dist', 'aura-basetools', 'bin', 'aura.mjs')
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'aura-entity-bench-'))
const cache = path.join(tmp, 'cache')
const env = { ...process.env, AURA_CACHE_DIR: cache }
const median = (xs) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)]
const lastJson = (text) => {
  const lines = String(text ?? '').trim().split('\n').filter(Boolean)
  for (let i = lines.length - 1; i >= 0; i -= 1) {
    try { return JSON.parse(lines[i]) } catch { /* keep looking */ }
  }
  return null
}
const runCli = (args) => {
  const t0 = performance.now()
  const res = spawnSync(process.execPath, [cli, ...args], { cwd: tmp, env, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
  return { ms: performance.now() - t0, status: res.status, env: lastJson(res.stdout), stderr: String(res.stderr ?? '') }
}
const makeSource = (functions) => {
  const out = ['// generated by probes/entity-bench.mjs']
  for (let i = 0; i < functions; i += 1) out.push(`export function fn${i}(value) {`, `  return value + ${i}`, '}')
  return `${out.join('\n')}\n`
}
